    function t(s, v) {
        var r = s;
        if (lang === 'ar') {
            if (AR[s] !== undefined) r = AR[s];
            else {
                var m = /^Season (\d+)$/.exec(s);
                if (m) r = 'الموسم ' + m[1];
                else if ((m = /^Account status: (.+)$/.exec(s))) r = 'حالة الحساب: ' + m[1];
            }
        }
        if (v) r = r.replace(/\{(\w+)\}/g, function (x, k) { return v[k] !== undefined ? v[k] : x; });
        return r;
    }

    function setLang(l) {
        lang = l === 'ar' ? 'ar' : 'en';
        var root = document.documentElement;
        root.setAttribute('lang', lang);
        root.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');
        if (document.body) document.body.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');
        root.classList.toggle('rtl', lang === 'ar');
    }

    function apply() {
        var a = document.querySelectorAll('[data-i18n]');
        for (var i = 0; i < a.length; i++) a[i].textContent = t(a[i].getAttribute('data-i18n'));
        var b = document.querySelectorAll('[data-i18n-ph]');
        for (var j = 0; j < b.length; j++) b[j].setAttribute('placeholder', t(b[j].getAttribute('data-i18n-ph')));
    }

    function isRtl() { return lang === 'ar'; }

    function dir() { return lang === 'ar' ? 'rtl' : 'ltr'; }

    function getLang() { return lang; }

